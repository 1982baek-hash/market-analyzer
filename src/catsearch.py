SYN_MAP = {w: codes for words, codes in SYN.items() for w in words}


def tokens(q: str) -> list[str]:
    return [t for t in re.split(r"[,\s·/、]+", (q or "").strip().lower()) if t]


def search(cats: pd.DataFrame, q: str, limit: int = 15) -> list[str]:
    """cats: inds_scls_cd, inds_scls_nm, inds_mcls_nm 열. 이름에 들어간 업종 먼저, 그다음 비슷한 말."""
    out: list[str] = []
    nm = cats["inds_scls_nm"].str.lower()
    mn = cats["inds_mcls_nm"].fillna("").str.lower() if "inds_mcls_nm" in cats else nm
    valid = set(cats["inds_scls_cd"])
    for t in tokens(q):
        hits = [] if len(t) == 1 and t in SYN_MAP else list(cats.loc[nm.str.contains(t, regex=False), "inds_scls_cd"])
        hits += [c for c in SYN_MAP.get(t, []) if c in valid]
        if not hits and len(t) >= 2:
            hits = list(cats.loc[mn.str.contains(t, regex=False), "inds_scls_cd"])
        if not hits:  # '떡볶이집'처럼 덧붙인 말: 비슷한 말이 그 안에 들어 있으면
            hits = [c for w, cs in SYN_MAP.items() if len(w) >= 2 and w in t for c in cs if c in valid]
        for c in hits:
            if c not in out:
                out.append(c)
    return out[:limit]
